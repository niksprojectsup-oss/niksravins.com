export function PortalIcon({
  name,
  className,
}: {
  name: PortalIconName;
  className?: string;
}) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.5"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={cn("h-4 w-4 shrink-0", className)}
    >
      {PATHS[name]}
    </svg>
  );
}

const BADGE_TONE = {
  sand: "bg-[#f3eadf] text-[#8a6248]",
  sage: "bg-[#e7f0ea] text-[#3f6b4e]",
  ivory: "bg-[#f7f1e8] text-[#6d5a45]",
} as const;

export function PortalIconBadge({
  name,
  tone = "sand",
  className,
}: {
  name: PortalIconName;
  tone?: keyof typeof BADGE_TONE;
  className?: string;
}) {
  return (
    <span
      aria-hidden="true"
      className={cn(
        "inline-flex h-9 w-9 shrink-0 items-center justify-center rounded-full",
        BADGE_TONE[tone],
        className,
      )}
    >
      <PortalIcon name={name} />
    </span>
  );
}

export function growthDimensionIcon(key: AssessmentDimensionKey): PortalIconName {
  return GROWTH_ICONS[key];
}

export function checkInMoodIcon(key: CheckInMoodKey): PortalIconName {
  return MOOD_ICONS[key];
}
